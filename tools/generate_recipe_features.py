"""Generate typed feature payload sizes from local pinned Vulkan headers (exclude padding/pointers)."""
from pathlib import Path
import re
import hashlib
import json

repo=Path(__file__).resolve().parents[1]
device=repo/'src/yuzu_video_core/vulkan_common/vulkan_device.h'
headers=[repo/'external/vulkan-headers/include/vulkan/vulkan_core.h',repo/'external/vulkan-headers/include/vulkan/vulkan_beta.h']
source='\n'.join(p.read_text() for p in headers)
macro_source=device.read_text().split('// Define miscellaneous extensions')[0].replace('\\\n','').replace('\\\r\n','')
groups=[re.search(r'#define FOR_EACH_VK_FEATURE_'+name+r'\(FEATURE\)(.*?)(?=\n\s*#define|\n\s*//|$)',macro_source,re.S).group(1) for name in ['1_1','1_2','1_3','EXT']]
out=['// SPDX-License-Identifier: GPL-2.0-or-later\n// Generated by tools/generate_recipe_features.py; typed last member excludes padding.\n#pragma once\n#include <cstddef>\n#include <vulkan/vulkan.h>\nnamespace Vulkan::RecipeFeatures {\ninline std::size_t PayloadBytes(VkStructureType type) {\nif(type==VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_FEATURES_2) return sizeof(VkPhysicalDeviceFeatures);\n']
count=0
for group_index,group in enumerate(groups):
    for prefix,name,macro,var in re.findall(r'FEATURE\((\w+),\s*(\w+),\s*(\w+),\s*(\w+)\)',group):
        typename='VkPhysicalDevice'+name+'Features'+(prefix if group_index==3 else '')
        structname=typename
        for _ in range(5):
            body=re.search(r'typedef struct '+re.escape(structname)+r'\s*\{(.*?)\}\s*'+re.escape(structname)+r';',source,re.S)
            if body:break
            alias=re.search(r'typedef\s+(Vk\w+)\s+'+re.escape(structname)+r';',source)
            assert alias,structname
            structname=alias[1]
        assert body,typename
        fields=re.findall(r'VkBool32\s+(\w+)\s*;',body[1]);assert fields,typename
        # Every payload field in feature nodes must be bool32; only their headers are pointers.
        stripped=re.sub(r'VkStructureType\s+sType\s*;|void\s*\*\s*pNext\s*;|VkBool32\s+\w+\s*;','',body[1]).strip()
        assert not stripped,(typename,stripped)
        enum='VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_'+macro+'_FEATURES'+('_'+prefix if group_index==3 else '')
        out.append('if(type=='+enum+') { static_assert(offsetof('+typename+','+fields[0]+')==sizeof(VkBaseInStructure)); return offsetof('+typename+','+fields[-1]+')+sizeof(VkBool32)-sizeof(VkBaseInStructure); }\n')
        count+=1
out.append('return 0;\n}\n} // namespace Vulkan::RecipeFeatures\n')
target=repo/'src/yuzu_video_core/vulkan_common/vk_recipe_features.h'
target.write_text(''.join(out))
print(json.dumps({'generated':str(target),'feature_types':count,'sha256':hashlib.sha256(target.read_bytes()).hexdigest()}))
